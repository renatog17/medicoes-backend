CREATE TABLE instalacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL REFERENCES clientes(id),
    imovel_id BIGINT NOT NULL REFERENCES imoveis(id),
    medidor_id BIGINT NOT NULL REFERENCES medidores(id),
    data_inicio TIMESTAMP WITH TIME ZONE NOT NULL,
    data_fim TIMESTAMP WITH TIME ZONE,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    observacoes VARCHAR(2000),
    versao BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ck_instalacao_periodo CHECK (data_fim IS NULL OR data_fim > data_inicio)
);

CREATE INDEX idx_instalacoes_cliente ON instalacoes(cliente_id);
CREATE INDEX idx_instalacoes_imovel ON instalacoes(imovel_id);
CREATE INDEX idx_instalacoes_medidor ON instalacoes(medidor_id);

-- Um medidor pode ter varias instalacoes historicas, mas apenas uma aberta.
CREATE UNIQUE INDEX uk_instalacoes_medidor_ativo
    ON instalacoes(medidor_id) WHERE data_fim IS NULL;
