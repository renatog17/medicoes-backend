CREATE TABLE faturas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instalacao_id BIGINT NOT NULL REFERENCES instalacoes(id),
    medicao_anterior_id BIGINT NOT NULL REFERENCES medicoes(id),
    medicao_atual_id BIGINT NOT NULL REFERENCES medicoes(id),
    competencia VARCHAR(7) NOT NULL,
    consumo NUMERIC(19,6) NOT NULL CHECK (consumo >= 0),
    tarifa NUMERIC(19,6) NOT NULL CHECK (tarifa > 0),
    total NUMERIC(19,2) NOT NULL CHECK (total >= 0),
    emissao DATE NOT NULL,
    vencimento DATE NOT NULL,
    criada_em TIMESTAMP WITH TIME ZONE NOT NULL,
    situacao VARCHAR(30) NOT NULL,
    banco_id VARCHAR(255) UNIQUE,
    pix TEXT,
    situacao_bancaria VARCHAR(30),
    valor_pago NUMERIC(19,2),
    pago_em TIMESTAMP WITH TIME ZONE,
    versao BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_fatura_competencia UNIQUE (instalacao_id, competencia)
);
CREATE INDEX idx_faturas_situacao ON faturas(situacao);

