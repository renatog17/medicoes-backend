CREATE TABLE medicoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instalacao_id BIGINT NOT NULL REFERENCES instalacoes(id),
    data_medicao TIMESTAMP WITH TIME ZONE NOT NULL,
    leitura NUMERIC(19,6) NOT NULL,
    CONSTRAINT ck_medicoes_leitura CHECK (leitura >= 0)
);

CREATE INDEX idx_medicoes_instalacao ON medicoes(instalacao_id);
