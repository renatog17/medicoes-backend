CREATE TABLE clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL CHECK (btrim(nome) <> ''),
    cin VARCHAR(11) NOT NULL CONSTRAINT uk_clientes_cin UNIQUE CHECK (cin ~ '^[0-9]{11}$'),
    excluido BOOLEAN NOT NULL DEFAULT FALSE,
    email VARCHAR(254),
    telefone VARCHAR(30),
    endereco_cobranca_id BIGINT NOT NULL REFERENCES enderecos(id)
);

CREATE INDEX idx_clientes_endereco_cobranca ON clientes(endereco_cobranca_id);
